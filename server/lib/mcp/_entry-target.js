import { createHash } from 'node:crypto';
import { z } from 'zod';

// A revision of the complete item array also protects legacy entries without
// UUIDs, including identical entries whose indices would otherwise be ambiguous.
export function itemsRevision(items) {
  return createHash('sha256').update(JSON.stringify(items)).digest('hex');
}
export const entryTargetSchema = {
  entry_id: z.string().min(1).max(200).optional(),
  entry_index: z.number().int().min(0).optional(),
  expected_revision: z.string().regex(/^[a-f0-9]{64}$/),
};

// Called only after loading this authenticated user's day, inside the write
// transaction. Never accept a bare index or a revision generated by a write.
export function resolveEntryTarget(items, {entry_id, entry_index, expected_revision}) {
  if (typeof expected_revision !== 'string' || expected_revision !== itemsRevision(items)) {
    throw new RangeError('CONFLICT: diary items changed or expected_revision is missing. Read list_diary_entries again before confirming.');
  }
  let index = entry_index;
  if (entry_id !== undefined) {
    const matches = items.flatMap((item, i) => item.uuid === entry_id ? [i] : []);
    if (matches.length !== 1) throw new RangeError('Entry ID is missing or ambiguous in this user/day. Read the diary again.');
    if (index !== undefined && index !== matches[0]) throw new RangeError('CONFLICT: entry_id and entry_index refer to different entries.');
    index = matches[0];
  }
  if (!Number.isInteger(index) || index < 0 || index >= items.length) {
    throw new RangeError('Select one existing entry_id (preferred) or entry_index from list_diary_entries.');
  }
  return index;
}
